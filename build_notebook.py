md("""# Did the New Shop Format Work? — Causal Impact of a Staggered Store Remodel
**Daily Data Analytics Project · Day 17**

## Business question
*A fuel-station network in Azerbaijan runs a convenience shop at each of its **60 stations** (Baku city, highways, regional towns). Since April 2025 it has remodelled **24 shops** to a new format (coffee bar, hot food, self-checkout) in three waves: April 2025, October 2025 and April 2026. Each remodel costs AZN 150–230k and closes the shop for two weeks. The board now has to approve wave 4 and asks: **how much extra revenue did the remodel really cause, does it differ by location, and which stations should be next?***

Why this is hard:
* The remodelled shops were **not chosen at random**: management picked the biggest shops first, so "remodelled vs not" compares big shops with small ones.
* Revenue moves for reasons that have nothing to do with the remodel: growth, New Year and Novruz peaks, a **fuel-price rise in January 2026**, and a strong **summer peak on highways** that Baku city shops don't have.
* Waves start at different dates and the effect **ramps up** over several weeks. A standard two-way fixed-effects regression is known to be biased in this setting.

Approach: naive comparisons → two-way fixed effects (TWFE) → **stratified difference-in-differences with never-remodelled controls** (Callaway–Sant'Anna style, written from scratch), event study and pre-trend checks, cluster bootstrap → **synthetic control** for the flagship drive-through station with placebo inference → ROI and payback per location type. Because the data is synthetic, every estimate is also checked against the **true effect** the generator used.

> Data is **synthetic** (fixed seed), generated by `data/generate_data.py`. Stations and the company are fictional.""")

