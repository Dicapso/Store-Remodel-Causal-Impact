w, synth = c.synth_path(Y, FL, donors, pre_mask)
gap = Y.loc[FL].to_numpy() - synth
ratio_fl = c.rmspe(gap, post_mask) / c.rmspe(gap, pre_mask)
plac = {}
for d in donors:
    others = [x for x in donors if x != d]
    _, sy = c.synth_path(Y, d, others, pre_mask)
